package com.javaschoollab.content;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.annotation.PostConstruct;
import java.io.IOException;
import java.io.InputStream;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Service;

/**
 * Serves the course content that lives as JSON in src/main/resources/content (generated by `npm run export:content`).
 *
 * The files are served as the raw bytes, never parsed and re-written, so what the app receives is exactly what was
 * exported. The ~21 MB of courses are not read at startup: each file is read on first request, checked against the
 * SHA-256 in manifest.json, and kept in memory.
 */
@Service
public class ContentService {

    private static final Logger log = LoggerFactory.getLogger(ContentService.class);
    private static final String BASE = "content/";

    /** One course as listed in the manifest. */
    record Item(String id, String name, String file, String sha256) {}

    /** A file ready to serve, with its quoted strong ETag. */
    public record Payload(byte[] bytes, String etag) {}

    /** The file does not match its manifest hash (or cannot be read), so it must not be served. */
    public static class IntegrityException extends RuntimeException {
        public IntegrityException(String message) { super(message); }
    }

    private final ObjectMapper json;
    private final Map<String, Item> items = new LinkedHashMap<>();
    private final Map<String, byte[]> cache = new ConcurrentHashMap<>();
    private Payload index;
    private Payload manifest;

    public ContentService(ObjectMapper json) {
        this.json = json;
    }

    @PostConstruct
    void load() throws IOException {
        byte[] manifestBytes = read(BASE + "manifest.json");
        JsonNode m = json.readTree(manifestBytes);
        for (JsonNode i : m.get("items")) {
            Item item = new Item(i.get("id").asText(), i.get("name").asText(), i.get("file").asText(), i.get("sha256").asText());
            items.put(item.id(), item);
        }
        byte[] indexBytes = read(BASE + "index.json");
        manifest = new Payload(manifestBytes, etagOf(sha256(manifestBytes)));
        index = new Payload(indexBytes, etagOf(sha256(indexBytes)));
        log.info("Course content: {} courses, {} modules, {} topics (course files are read on first request)",
                m.get("courses").asInt(), m.get("totals").get("modules").asInt(), m.get("totals").get("topics").asInt());
    }

    public Payload index() { return index; }

    public Payload manifest() { return manifest; }

    /** The full course, or empty if the id is unknown. Throws {@link IntegrityException} if the file was altered. */
    public Optional<Payload> course(String id) {
        Item item = items.get(id);
        if (item == null) return Optional.empty();
        try {
            byte[] bytes = cache.computeIfAbsent(id, k -> {
                try {
                    return verified(item, read(BASE + item.file()));
                } catch (IOException e) {
                    throw new IntegrityException("Course file could not be read: " + item.file());
                }
            });
            return Optional.of(new Payload(bytes, etagOf(item.sha256())));
        } catch (IntegrityException e) {
            log.error("Course content integrity check failed for '{}': {}", id, e.getMessage());
            throw e;
        }
    }

    /** Returns the bytes if their SHA-256 equals the manifest's, otherwise throws. */
    byte[] verified(Item item, byte[] bytes) {
        String actual = sha256(bytes);
        if (!actual.equalsIgnoreCase(item.sha256())) {
            throw new IntegrityException("SHA-256 mismatch for " + item.file() + " (manifest " + item.sha256() + ", file " + actual + ")");
        }
        return bytes;
    }

    private static String etagOf(String sha) { return "\"" + sha + "\""; }

    private static byte[] read(String path) throws IOException {
        try (InputStream in = new ClassPathResource(path).getInputStream()) {
            return in.readAllBytes();
        }
    }

    static String sha256(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
